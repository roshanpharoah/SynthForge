def _timestep_embedding(t: torch.Tensor, dim: int) -> torch.Tensor:
    half = dim // 2
    freqs = torch.exp(-math.log(10000.0) * torch.arange(half, device=t.device, dtype=torch.float32) / max(half - 1, 1))
    args = t.float().unsqueeze(1) * freqs.unsqueeze(0)
    emb = torch.cat([torch.sin(args), torch.cos(args)], dim=1)
    if emb.shape[1] < dim:
        emb = F.pad(emb, (0, dim - emb.shape[1]))
    return emb


class _Gen2D(nn.Module):
    def __init__(self, noise: int, cond: int, out_ch: int, hidden: int, in_ch: int = 1):
        super().__init__()
        self.cond_dim = cond
        self.fc = nn.Linear(noise + cond, hidden * 4 * 4)
        self.hidden = hidden
        self.net = nn.Sequential(
            nn.ConvTranspose2d(hidden, hidden, 4, 2, 1),
            nn.BatchNorm2d(hidden),
            nn.ReLU(),
            nn.ConvTranspose2d(hidden, hidden // 2, 4, 2, 1),
            nn.BatchNorm2d(hidden // 2),
            nn.ReLU(),
            nn.ConvTranspose2d(hidden // 2, hidden // 4, 4, 2, 1),
            nn.BatchNorm2d(hidden // 4),
            nn.ReLU(),
            nn.Conv2d(hidden // 4, out_ch, 3, padding=1),
            nn.Tanh(),
        )
        self.noisy_proj = nn.Conv2d(in_ch, hidden, 3, padding=1)

    def forward(self, z: torch.Tensor, cond: torch.Tensor, noisy: torch.Tensor) -> torch.Tensor:
        h = self.fc(torch.cat([z, cond], dim=1)).view(z.shape[0], self.hidden, 4, 4)
        h = h + F.interpolate(self.noisy_proj(noisy), size=4, mode="bilinear", align_corners=False)
        return self.net(h)


class _Disc2D(nn.Module):
    def __init__(self, in_ch: int, cond: int, hidden: int):
        super().__init__()
        self.net = nn.Sequential(
            nn.Conv2d(in_ch, hidden // 4, 4, 2, 1),
            nn.LeakyReLU(0.2),
            nn.Conv2d(hidden // 4, hidden // 2, 4, 2, 1),
            nn.LeakyReLU(0.2),
            nn.Conv2d(hidden // 2, hidden, 4, 2, 1),
            nn.LeakyReLU(0.2),
        )
        self.head = nn.Linear(hidden + cond, 1)

    def forward(self, x: torch.Tensor, cond: torch.Tensor) -> torch.Tensor:
        h = self.net(x)
        h = F.adaptive_avg_pool2d(h, 1).flatten(1)
        return self.head(torch.cat([h, cond], dim=1))


class _Gen3D(nn.Module):
    def __init__(self, noise: int, cond: int, out_ch: int, hidden: int, in_ch: int = 1, seed_size: int = 4):
        super().__init__()
        self.seed = seed_size
        self.hidden = hidden
        self.fc = nn.Linear(noise + cond, hidden * seed_size**3)
        self.net = nn.Sequential(
            nn.ConvTranspose3d(hidden, hidden // 2, 4, 2, 1),
            nn.BatchNorm3d(hidden // 2),
            nn.ReLU(),
            nn.ConvTranspose3d(hidden // 2, hidden // 4, 4, 2, 1),
            nn.BatchNorm3d(hidden // 4),
            nn.ReLU(),
            nn.Conv3d(hidden // 4, out_ch, 3, padding=1),
            nn.Tanh(),
        )
        self.noisy_proj = nn.Conv3d(in_ch, hidden, 3, padding=1)

    def forward(self, z: torch.Tensor, cond: torch.Tensor, noisy: torch.Tensor) -> torch.Tensor:
        h = self.fc(torch.cat([z, cond], dim=1)).view(z.shape[0], self.hidden, self.seed, self.seed, self.seed)
        h = h + F.interpolate(self.noisy_proj(noisy), size=self.seed, mode="trilinear", align_corners=False)
        return self.net(h)


class _Disc3D(nn.Module):
    def __init__(self, in_ch: int, cond: int, hidden: int):
        super().__init__()
        self.net = nn.Sequential(
            nn.Conv3d(in_ch, hidden // 4, 4, 2, 1),
            nn.LeakyReLU(0.2),
            nn.Conv3d(hidden // 4, hidden // 2, 4, 2, 1),
            nn.LeakyReLU(0.2),
            nn.Conv3d(hidden // 2, hidden, 4, 2, 1),
            nn.LeakyReLU(0.2),
        )
        self.head = nn.Linear(hidden + cond, 1)

    def forward(self, x: torch.Tensor, cond: torch.Tensor) -> torch.Tensor:
        h = self.net(x)
        h = F.adaptive_avg_pool3d(h, 1).flatten(1)
        return self.head(torch.cat([h, cond], dim=1))


class _MaskHead(nn.Module):
    def __init__(self, in_ch: int, hidden: int):
        super().__init__()
        self.net = nn.Sequential(
            nn.Conv2d(in_ch, hidden // 4, 3, padding=1),
            nn.ReLU(),
            nn.Conv2d(hidden // 4, hidden // 8, 3, padding=1),
            nn.ReLU(),
            nn.Conv2d(hidden // 8, 1, 1),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.net(x)


class DiffuseGANSynthesizer:
    model_name = "diffusion"
    modality = "imaging"
    _gen_cls = _Gen2D
    _disc_cls = _Disc2D

    def __init__(self, config: RunConfig | None = None):
        self.config = config or RunConfig()
        self.generator: nn.Module | None = None
        self.discriminator: nn.Module | None = None
        self.mask_head: _MaskHead | None = None
        self.history = TrainHistory()
        self.report: PrivacyReport | None = None
        self.warnings: list[str] = []
        self.metadata: dict[str, Any] = {}
        self.is_fitted = False
        self.is_3d = False
        self.shape: tuple[int, ...] = (32, 32)
        self.channels = 1
        self.cond_labels: list[str] = []
        self.cond_stats: dict[str, pd.Series] = {}
        self.label_classes: dict[str, list[str]] = {}
        self.has_masks = False
        self.device = torch.device("cpu")
        self._min_max = (0.0, 1.0)

    # ------------------------------------------------------------------ setup
    def _encode_labels(self, labels: pd.DataFrame, n: int, *, sampling: bool, seed: int = 0) -> np.ndarray:
        rng = np.random.default_rng(seed)
        parts: list[np.ndarray] = []
        for col in self.cond_labels:
            if col in self.label_classes:
                classes = self.label_classes[col]
                vec = np.zeros((n, len(classes)), dtype=np.float32)
                if sampling:
                    probs = self.cond_stats[col].to_numpy(dtype=float)
                    probs = probs / max(probs.sum(), 1e-12)
                    idx = rng.choice(len(classes), size=n, p=probs)
                else:
                    vals = labels[col].astype(str) if col in labels.columns else pd.Series([classes[0]] * n)
                    idx = np.array([classes.index(v) if v in classes else 0 for v in vals])
                vec[np.arange(n), idx] = 1.0
                parts.append(vec)
            else:
                stats = self.cond_stats[col]
                if sampling:
                    vals = stats.sample(n, replace=True, random_state=int(rng.integers(0, 1 << 31))).to_numpy(dtype=float)
                else:
                    vals = pd.to_numeric(labels[col], errors="coerce").fillna(float(stats.mean())).to_numpy(dtype=float)
                mu, sd = float(stats.mean()), float(stats.std() or 1.0)
                parts.append(((vals - mu) / sd).astype(np.float32)[:, None])
        return np.concatenate(parts, axis=1) if parts else np.zeros((n, 0), dtype=np.float32)

    def _cond_dim(self) -> int:
        return sum(len(self.label_classes[c]) if c in self.label_classes else 1 for c in self.cond_labels)

    def _prepare(self, dataset: Dataset, config: RunConfig) -> tuple[np.ndarray, np.ndarray | None, pd.DataFrame]:
        if dataset.images is None:
            raise ModelError(
                "the imaging model requires image data",
                hint="Ingest NIfTI or DICOM data first.",
            )
        cohort: ImageCohort = dataset.images
        images = np.asarray(cohort.images, dtype=np.float32)
        if images.ndim == 3:
            images = images[:, None, :, :]
        if images.shape[0] < 4:
            raise ModelError("at least 4 images are required to train an imaging generator")
        self.is_3d = images.ndim == 5
        self.shape = tuple(images.shape[2:])
        self.channels = images.shape[1]
        target = int(config.training.resolution)
        if not self.is_3d and self.shape != (target, target):
            images = torch.nn.functional.interpolate(
                torch.tensor(images), size=(target, target), mode="bilinear", align_corners=False
            ).numpy()
            self.shape = (target, target)
        masks = None
        if cohort.masks is not None:
            masks = np.asarray(cohort.masks, dtype=np.float32)
            if masks.ndim == 3:
                masks = masks[:, None, :, :]
            if not self.is_3d and masks.shape[2:] != self.shape:
                masks = torch.nn.functional.interpolate(
                    torch.tensor(masks), size=self.shape, mode="nearest"
                ).numpy()
            self.has_masks = True
        lo, hi = float(images.min()), float(images.max())
        self._min_max = (lo, hi if hi > lo else lo + 1.0)
        images = 2.0 * (images - self._min_max[0]) / (self._min_max[1] - self._min_max[0]) - 1.0
        return images.astype(np.float32), (masks.astype(np.float32) if masks is not None else None), cohort.labels.reset_index(drop=True)

    # ------------------------------------------------------------------ fit
    def fit(
        self,
        dataset: Dataset,
        config: RunConfig,
        *,
        progress: ProgressCallback | None = None,
        should_cancel: CancelCheck | None = None,
        checkpoint_dir: str | Path | None = None,
    ) -> FitResult:
        started = time.time()
        self.config = config
        images, masks, labels = self._prepare(dataset, config)
        if config.privacy.enabled:
            self.warnings.append("The imaging generator has no accounted DP path; this run is non-private.")
        for col in ("lesion", "age", "contrast"):
            if col in labels.columns:
                self.cond_labels.append(col)
                s = labels[col]
                if s.nunique(dropna=True) <= 6 and not pd.api.types.is_numeric_dtype(s):
                    self.label_classes[col] = sorted(s.dropna().astype(str).unique().tolist())
                    counts = s.astype(str).value_counts()
                    self.cond_stats[col] = pd.Series([counts.get(c, 0) for c in self.label_classes[col]], dtype=float)
                elif pd.api.types.is_numeric_dtype(s) or col == "lesion":
                    self.cond_stats[col] = pd.to_numeric(s, errors="coerce").dropna()
                else:
                    self.label_classes[col] = sorted(s.dropna().astype(str).unique().tolist())[:6]
                    counts = s.astype(str).value_counts()
                    self.cond_stats[col] = pd.Series([counts.get(c, 0) for c in self.label_classes[col]], dtype=float)
        self.device = torch.device("cuda" if (config.training.device in ("auto", "cuda") and torch.cuda.is_available()) else "cpu")
        noise = int(config.training.latent_dim)
        hidden = int(config.training.hidden_dim)
        cond_dim = self._cond_dim()
        in_ch = self.channels
        if self.is_3d:
            gen3 = _Gen3D(noise, cond_dim, self.channels, hidden, in_ch=self.channels)
            disc3 = _Disc3D(in_ch, cond_dim, hidden)
            self.generator = gen3.to(self.device)
            self.discriminator = disc3.to(self.device)
        else:
            gen2 = _Gen2D(noise, cond_dim, self.channels, hidden, in_ch=self.channels)
            disc2 = _Disc2D(in_ch, cond_dim, hidden)
            self.generator = gen2.to(self.device)
            self.discriminator = disc2.to(self.device)
        if self.has_masks and not self.is_3d:
            self.mask_head = _MaskHead(self.channels, hidden).to(self.device)
        params_g = list(self.generator.parameters()) + (list(self.mask_head.parameters()) if self.mask_head else [])
        opt_g = torch.optim.Adam(params_g, lr=float(config.training.lr), betas=(0.5, 0.999))
        opt_d = torch.optim.Adam(self.discriminator.parameters(), lr=float(config.training.lr), betas=(0.5, 0.999))
        torch.manual_seed(config.seed)
        data = torch.tensor(images, dtype=torch.float32)
        mask_t = torch.tensor(masks, dtype=torch.float32) if masks is not None else None
        n = len(data)
        batch = min(int(config.training.batch_size), n)
        steps_per_epoch = max(1, n // batch)
        max_steps = int(config.training.max_steps or config.training.epochs * steps_per_epoch)
        cond_all = torch.tensor(self._encode_labels(labels, n, sampling=False), dtype=torch.float32)
        losses: dict[str, list[float]] = {"discriminator": [], "generator": []}
        steps_done = 0
        for epoch in range(int(config.training.epochs)):
            ep_d, ep_g = [], []
            steps_this = min(steps_per_epoch, max_steps - steps_done)
            if steps_this <= 0:
                break
            for step in range(steps_this):
                if should_cancel and should_cancel():
                    self.history = self._history(losses, steps_done, epoch + 1, started, True)
                    raise CancelledError("training cancelled by request")
                rng = np.random.default_rng(config.seed * 6151 + epoch * 277 + step)
                idx = torch.as_tensor(rng.integers(0, n, size=batch))
                real = data[idx].to(self.device)
                cond = cond_all[idx].to(self.device)
                t = torch.rand(batch, device=self.device)
                sigma = (0.05 + 0.55 * t).view(batch, *([1] * (real.dim() - 1)))
                noisy = real + sigma * torch.randn_like(real) * 0.6
                t_emb = _timestep_embedding(t, cond_dim)
                cond_t = cond + t_emb
                z = torch.randn(batch, noise, device=self.device)
                fake = self.generator(z, cond_t, noisy)
                # discriminator
                opt_d.zero_grad(set_to_none=True)
                real_score = self.discriminator(real, cond)
                fake_score = self.discriminator(fake.detach(), cond)
                alpha = torch.rand(batch, *([1] * (real.dim() - 1)), device=self.device)
                interp = (alpha * real + (1 - alpha) * fake.detach()).requires_grad_(True)
                iscore = self.discriminator(interp, cond)
                grads = torch.autograd.grad(iscore.sum(), interp, create_graph=True)[0]
                gp = ((grads.flatten(1).norm(2, dim=1) - 1) ** 2).mean()
                d_loss = fake_score.mean() - real_score.mean() + 10.0 * gp
                d_loss.backward()
                opt_d.step()
                # generator (+ mask aux)
                opt_g.zero_grad(set_to_none=True)
                z2 = torch.randn(batch, noise, device=self.device)
                t2 = torch.rand(batch, device=self.device)
                sigma2 = (0.05 + 0.55 * t2).view(batch, *([1] * (real.dim() - 1)))
                noisy2 = real + sigma2 * torch.randn_like(real) * 0.6
                cond_t2 = cond + _timestep_embedding(t2, cond_dim)
                fake2 = self.generator(z2, cond_t2, noisy2)
                g_loss = -self.discriminator(fake2, cond).mean()
                if self.mask_head is not None and mask_t is not None:
                    m_real = mask_t[idx].to(self.device)
                    m_pred = self.mask_head(fake2)
                    bce = F.binary_cross_entropy_with_logits(m_pred, m_real)
                    probs = torch.sigmoid(m_pred)
                    dice = 1 - (2 * (probs * m_real).sum() + 1) / (probs.sum() + m_real.sum() + 1)
                    g_loss = g_loss + 0.6 * bce + 1.4 * dice
                    losses.setdefault("mask_bce", []).append(float(bce.item()))
                    losses.setdefault("mask_dice_loss", []).append(float(dice.item()))
                g_loss.backward()
                opt_g.step()
                steps_done += 1
                ep_d.append(float(d_loss.item()))
                ep_g.append(float(g_loss.item()))
                if progress and step % max(1, steps_per_epoch // 6) == 0:
                    payload = {
                        "phase": "train",
                        "epoch": epoch + 1,
                        "epochs": int(config.training.epochs),
                        "step": steps_done,
                        "max_steps": max_steps,
                        "discriminator_loss": float(np.mean(ep_d)),
                        "generator_loss": float(np.mean(ep_g)),
                        "progress": min(0.98, 0.05 + 0.92 * steps_done / max(max_steps, 1)),
                        "device": str(self.device),
                    }
                    if losses.get("mask_bce"):
                        payload["mask_bce"] = float(np.mean(losses["mask_bce"][-steps_this:]))
                    progress(payload)
            losses["discriminator"].append(float(np.mean(ep_d)))
            losses["generator"].append(float(np.mean(ep_g)))
            if steps_done >= max_steps:
                break
            if checkpoint_dir and (epoch + 1) % int(config.training.checkpoint_every) == 0:
                self._checkpoint(Path(checkpoint_dir) / "checkpoint.pt", epoch, noise, hidden, cond_dim)
            if progress:
                preview = self._preview_grid(4)
                progress({"phase": "sample", "epoch": epoch + 1, "preview": preview})
        self.is_fitted = True
        self.history = self._history(losses, steps_done, int(config.training.epochs), started, False)
        self.metadata = {
            "architecture": "DiffuseGAN: timestep-conditioned generator + PatchGAN critic + WGAN-GP",
            "is_3d": self.is_3d,
            "shape": list(self.shape),
            "channels": self.channels,
            "condition_labels": self.cond_labels,
            "mask_auxiliary": self.mask_head is not None,
            "device": str(self.device),
            "deviations": [
                "The generator predicts images in one shot at a sampled noise level; it is not an iterative denoising sampler.",
                "No DP accounting exists for the imaging path.",
            ],
        }
        self.report = PrivacyReport(
            mechanism="non-private",
            statement="Non-private run: no differential-privacy guarantee is claimed for image synthesis.",
            excluded=["No differential privacy."],
        )
        if progress:
            progress({"phase": "done", "progress": 1.0, "epsilon": None, "step": steps_done})
        return FitResult(history=self.history, device=str(self.device), n_train_rows=n, warnings=self.warnings, metadata=self.metadata)

    def _checkpoint(self, path: Path, epoch: int, noise: int, hidden: int, cond_dim: int) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        torch.save(
            {
                "generator": self.generator.state_dict() if self.generator else None,
                "discriminator": self.discriminator.state_dict() if self.discriminator else None,
                "mask_head": self.mask_head.state_dict() if self.mask_head else None,
                "epoch": epoch,
                "noise": noise,
                "hidden": hidden,
                "cond_dim": cond_dim,
                "history": self.history.model_dump(mode="json"),
            },
            str(path),
        )

    def _history(self, losses: dict[str, list[float]], steps: int, epochs: int, started: float, early: bool) -> TrainHistory:
        return TrainHistory(
            steps=int(steps),
            epochs=int(epochs),
            losses={k: [float(x) for x in v] for k, v in losses.items()},
            early_stopped=early,
            duration_seconds=time.time() - started,
        )

    def _preview_grid(self, n: int = 4) -> dict[str, Any]:
        try:
            ds = self.sample(n, seed=self.config.seed + 1234)
            arr = ds.images.images if ds.images else None
            if arr is None:
                return {}
            arr = arr[:n]
            if arr.ndim == 4:
                arr = arr[:, 0]
            return {"shape": list(arr.shape), "min": float(arr.min()), "max": float(arr.max())}
        except Exception:
            return {}

    # ------------------------------------------------------------------ sampling
    def sample(
        self,
        n: int,
        *,
        conditions: dict[str, Any] | None = None,
        seed: int | None = None,
        table: str | None = None,
    ) -> Dataset:
        if not self.is_fitted or self.generator is None:
            raise ModelError("imaging generator is not fitted")
        conditions = dict(conditions or {})
        cond_vec = np.zeros((n, self._cond_dim()), dtype=np.float32)
        labels = pd.DataFrame(index=pd.RangeIndex(n))
        offset = 0
        rng = np.random.default_rng(int(seed if seed is not None else self.config.seed + 1))
        for col in self.cond_labels:
            if col in self.label_classes:
                classes = self.label_classes[col]
                want = conditions.get(col)
                if want is not None:
                    if str(want) not in classes:
                        raise ModelError(
                            f"unknown value {want!r} for condition {col!r}",
                            hint=f"Available: {', '.join(classes)}",
                        )
                    idx = np.full(n, classes.index(str(want)))
                else:
                    probs = self.cond_stats[col].to_numpy(dtype=float)
                    probs = probs / max(probs.sum(), 1e-12)
                    idx = rng.choice(len(classes), size=n, p=probs)
                cond_vec[np.arange(n), offset + idx] = 1.0
                labels[col] = [classes[i] for i in idx]
                offset += len(classes)
            else:
                stats = self.cond_stats[col]
                want = conditions.get(col)
                if want is not None:
                    vals = np.full(n, float(want))
                else:
                    vals = stats.sample(n, replace=True, random_state=int(rng.integers(0, 1 << 31))).to_numpy(dtype=float)
                mu, sd = float(stats.mean()), float(stats.std() or 1.0)
                cond_vec[:, offset] = (vals - mu) / sd
                labels[col] = vals
                offset += 1
        cond = torch.tensor(cond_vec, dtype=torch.float32, device=self.device)
        noise = int(self.config.training.latent_dim)
        gen = torch.Generator().manual_seed(int(seed if seed is not None else self.config.seed + 1))
        outs, mask_outs = [], []
        with torch.no_grad():
            for start in range(0, n, 64):
                m = min(64, n - start)
                z = torch.randn(m, noise, generator=gen).to(self.device)
                t = torch.full((m,), 0.85, device=self.device)
                t_emb = _timestep_embedding(t, self._cond_dim())
                c = cond[start : start + m]
                if self.is_3d:
                    noisy = torch.zeros((m, self.channels, *self.shape), device=self.device)
                else:
                    noisy = torch.zeros((m, self.channels, *self.shape), device=self.device)
                img = self.generator(z, c + t_emb, noisy)
                outs.append(img.cpu().numpy())
                if self.mask_head is not None and not self.is_3d:
                    mask_outs.append(torch.sigmoid(self.mask_head(img)).cpu().numpy())
        images = np.concatenate(outs, axis=0)
        lo, hi = self._min_max
        images = ((images + 1.0) / 2.0) * (hi - lo) + lo
        masks_np = np.concatenate(mask_outs, axis=0) if mask_outs else None
        if images.shape[1] == 1:
            images = images[:, 0]
            if masks_np is not None:
                masks_np = masks_np[:, 0]
        cohort = ImageCohort(
            images=images.astype(np.float32),
            masks=(masks_np.astype(np.float32) if masks_np is not None else None),
            labels=labels,
            spacing=tuple(self.metadata.get("spacing", [])),
            metadata={"synthetic": True, "model": "diffusion", "conditions": conditions},
        )
        return Dataset(
            name="images_synthetic",
            kind="imaging",
            images=cohort,
            synthetic=True,
            provenance={
                "model": self.model_name,
                "seed": int(seed if seed is not None else self.config.seed + 1),
                "n": n,
                "conditions": conditions,
                "note": "Synthetic phantoms/volumes from a fitted generator; not diagnostic images.",
            },
        )

    def interpolate(self, n: int, *, seed: int = 0, conditions: dict[str, Any] | None = None) -> Dataset:
        """Latent interpolation between two random latents (editing API)."""
        if not self.is_fitted or self.generator is None:
            raise ModelError("imaging generator is not fitted")
        gen = torch.Generator().manual_seed(seed)
        noise = int(self.config.training.latent_dim)
        z1 = torch.randn(1, noise, generator=gen)
        z2 = torch.randn(1, noise, generator=gen)
        alphas = torch.linspace(0, 1, n).view(n, 1)
        z = (1 - alphas) * z1 + alphas * z2
        ds = self.sample(n, seed=seed, conditions=conditions)
        # Re-run the generator with interpolated latents but identical conditioning.
        cond_guess = ds.images.labels if ds.images else pd.DataFrame()
        cond_vec = torch.tensor(self._encode_labels(cond_guess, n, sampling=False), dtype=torch.float32, device=self.device)
        t = torch.full((n,), 0.85, device=self.device)
        c = cond_vec + _timestep_embedding(t, self._cond_dim())
        if self.is_3d:
            noisy = torch.zeros((n, self.channels, *self.shape), device=self.device)
        else:
            noisy = torch.zeros((n, self.channels, *self.shape), device=self.device)
        with torch.no_grad():
            img = self.generator(z.to(self.device), c, noisy).cpu().numpy()
        lo, hi = self._min_max
        img = ((img + 1.0) / 2.0) * (hi - lo) + lo
        if img.shape[1] == 1:
            img = img[:, 0]
        ds.images.images = img.astype(np.float32) if ds.images else img
        ds.provenance["interpolation"] = {"alphas": alphas.flatten().tolist()[:16], "n": n}
        return ds

    # ------------------------------------------------------------------ persistence
    def save(self, path: str | Path) -> Path:
        root = Path(path)
        root.mkdir(parents=True, exist_ok=True)
        if not self.is_fitted:
            raise ModelError("cannot save an unfitted model")
        torch.save(
            {
                "generator": self.generator.state_dict() if self.generator else None,
                "discriminator": self.discriminator.state_dict() if self.discriminator else None,
                "mask_head": self.mask_head.state_dict() if self.mask_head else None,
                "is_3d": self.is_3d,
                "shape": list(self.shape),
                "channels": self.channels,
                "cond_labels": self.cond_labels,
                "label_classes": self.label_classes,
                "cond_stats": {k: v.to_dict() for k, v in self.cond_stats.items()},
                "has_masks": self.has_masks,
                "min_max": list(self._min_max),
                "metadata": self.metadata,
                "history": self.history.model_dump(mode="json"),
                "warnings": self.warnings,
                "model_name": self.model_name,
            },
            str(root / "images.pt"),
        )
        (root / "config.json").write_text(self.config.model_dump_json(indent=2), encoding="utf-8")
        if self.report is not None:
            (root / "privacy.json").write_text(self.report.model_dump_json(indent=2), encoding="utf-8")
        (root / "model_card.json").write_text(json.dumps(self.model_card(), indent=2, default=str), encoding="utf-8")
        return root

    def _build_networks(self, noise: int, hidden: int, cond_dim: int) -> None:
        in_ch = self.channels
        if self.is_3d:
            self.generator = _Gen3D(noise, cond_dim, self.channels, hidden, in_ch=self.channels)
            self.discriminator = _Disc3D(in_ch, cond_dim, hidden)
        else:
            self.generator = _Gen2D(noise, cond_dim, self.channels, hidden, in_ch=self.channels)
            self.discriminator = _Disc2D(in_ch, cond_dim, hidden)
            if self.has_masks:
                self.mask_head = _MaskHead(self.channels, hidden)

    @classmethod
    def load(cls, path: str | Path) -> DiffuseGANSynthesizer:
        root = Path(path)
        state = torch.load(str(root / "images.pt"), map_location="cpu", weights_only=False)
        obj = cls()
        obj.is_3d = bool(state["is_3d"])
        obj.shape = tuple(state["shape"])
        obj.channels = int(state["channels"])
        obj.cond_labels = list(state["cond_labels"])
        obj.label_classes = {k: list(v) for k, v in state["label_classes"].items()}
        obj.cond_stats = {k: pd.Series(v) for k, v in state["cond_stats"].items()}
        obj.has_masks = bool(state["has_masks"])
        obj._min_max = tuple(state["min_max"])
        obj.metadata = state.get("metadata", {})
        obj.history = TrainHistory.model_validate(state["history"])
        obj.warnings = state.get("warnings", [])
        cfg = root / "config.json"
        if cfg.exists():
            obj.config = RunConfig.model_validate_json(cfg.read_text(encoding="utf-8"))
        priv = root / "privacy.json"
        if priv.exists():
            obj.report = PrivacyReport.model_validate_json(priv.read_text(encoding="utf-8"))
        obj._build_networks(int(obj.config.training.latent_dim), int(obj.config.training.hidden_dim), obj._cond_dim())
        obj.generator.load_state_dict(state["generator"])
        if state.get("discriminator") is not None:
            obj.discriminator.load_state_dict(state["discriminator"])
        if state.get("mask_head") is not None and obj.mask_head is not None:
            obj.mask_head.load_state_dict(state["mask_head"])
        obj.is_fitted = True
        return obj

    def privacy_report(self) -> PrivacyReport:
        return self.report or PrivacyReport(mechanism="none")

    def model_card(self) -> dict[str, Any]:
        return {
            "model": self.model_name,
            "modality": "imaging",
            "version": "0.1.0",
            "intended_use": "Synthetic image generation for pipeline development, augmentation research and testing.",
            "out_of_scope": [
                "Clinical interpretation or diagnosis",
                "Any claim that generated images are anatomically faithful",
                "Regulatory submissions",
            ],
            "architecture": {
                "type": "DiffuseGAN (timestep-conditioned GAN with WGAN-GP critic)",
                "is_3d": self.is_3d,
                "shape": list(self.shape),
                "channels": self.channels,
                "mask_head": self.mask_head is not None,
                "conditioning": self.cond_labels,
            },
            "training": self.history.model_dump(mode="json"),
            "privacy_claim": (self.report.model_dump(mode="json") if self.report else {}),
            "limitations": self.warnings,
            "metadata": self.metadata,
        }


class PlainGANSynthesizer(DiffuseGANSynthesizer):
    """Plain DCGAN baseline without timestep conditioning (imaging)."""

    model_name = "gan"
    modality = "imaging"

    def fit(self, dataset: Dataset, config: RunConfig, **kwargs: Any) -> FitResult:  # type: ignore[override]
        result = super().fit(dataset, config, **kwargs)
