"""DiffuseGAN: diffusion-inspired GAN for small medical images (2D and 3D).

Design (documented honestly in the model card):
- The generator is conditioned on a *timestep embedding* and on labels, mimicking a denoiser:
  G(z, t, y) predicts the image directly at noise level t. Training samples t uniformly and blends the
  target with Gaussian noise; the generator sees the noisy image as an extra input channel, so it learns
  to act as a one-shot denoiser.
- The critic is a PatchGAN-style convolutional network with a timestep embedding and WGAN-GP penalty.
- Masks (segmentation) can be generated by an auxiliary mask head with a Dice + BCE objective, and
  conditioning on the `lesion` label is supported so rare pathologies can be augmented.
- Optional latent interpolation and label editing are exposed for downstream workflows.

This is not a score-based diffusion sampler with a proven likelihood; it is a GAN with diffusion-style
timestep conditioning, named accordingly.
"""

